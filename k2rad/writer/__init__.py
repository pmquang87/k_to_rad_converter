"""
k2rad.writer  –  Generate OpenRadioss Starter and Engine strings from
                 ConversionState.

Starter output order:
  BEGIN / TITLE / ANALY / DEF_SHELL / DEF_SOLID
  Materials → Nodes → BCS → SKEW → Parts+Elements → Properties
  Functions → Groups → Interfaces → RBODYs → IMPDISP/IMPVEL → TH → END

Engine output order:
  RUN / TFILE / PRINT / ANIM → IMPL/* → CLOAD

Package layout (split from the original single-module writer.py; every name
below is re-exported so ``k2rad.writer`` keeps the old flat namespace):

  common     – field formatting (_f/_i), group/surface emitters, vector math
  materials  – /MAT laws, EOS, failure cards, /FUNCT curves, table resolution
  composites – orthotropic/composite laws (LAW93/127/43/27 pair), the per-ply
               *PART_COMPOSITE layup (TYPE51+TYPE19) and the AOPT axis mapping
  mesh       – nodes, skews, parts+elements, TET10 handling, properties
  beams      – *INTEGRATION_BEAM cross-section rules → /PROP/TYPE18 (INT_BEAM),
               and the derived-section-constant fallback onto /PROP/BEAM
  contacts   – /INTER TYPE7/TYPE25/TYPE2, force transducers, contact warnings
  rbody      – /RBODY, constrained nodal rigid bodies, merges, probe body
  loads      – BCS, cloads, pressure, gravity, imposed motions, inivel,
               rigid walls, springs/connectors, added masses, damping
  blast_ale  – blast loads, detonations, ALE, FSI coupling, EBCS, INIVOL
  inistate   – /INISHE, /INIBRI initial stresses and /SECT cross-sections
  output     – header/title/analysis cards, time-history outputs, /EIG, notes
  assembly   – build_starter / build_engine and the engine-card emitters
"""

